import { MongoClient } from 'mongodb';
import { buildRoutes } from '../lib/routes.js';
import { ensureIndexes, seedDatabase } from '../lib/seed.js';
const client = await MongoClient.connect('mongodb://127.0.0.1:27018');
const db = client.db('agentic_lims_projects_test');
await db.dropDatabase();
await ensureIndexes(db); await seedDatabase(db);
const routes = buildRoutes({ db, config: { demoNow: '2026-10-27T08:00:00+08:00' } });
const call = async (path, body, method) => {
  const [p, q] = path.split('?');
  const verb = method || (body ? 'POST' : 'GET');
  const route = routes.find((r) => r.path === p && r.methods.includes(verb));
  const res = await route.fetch(new Request(`http://x${p}${q ? `?${q}` : ''}`, { method: verb, headers: body ? { 'content-type': 'application/json' } : {}, body: body ? JSON.stringify(body) : undefined }));
  return { status: res.status, data: await res.json() };
};
const projects = await call('/api/lims/projects');
console.log('projects', projects.data.projects.map(p => ({ id: p.id, name: p.name, tasks: p.taskCount, templates: p.templateNames, due: `${p.dueFromLabel}-${p.dueToLabel}` })));
const project = await call('/api/lims/project?projectId=PRJ-1001');
console.log('project groups', project.data.groups.map(g => ({ key: g.key, template: g.templateName, tasks: g.tasks.map(t => t.id), effort: g.effortHours })));
const group = project.data.groups[0];
const tp = await call('/api/lims/test-plan', { projectId: 'PRJ-1001', templateId: group.key });
console.log('test plan', tp.status, tp.data.testPlan?.id, tp.data.testPlan?.templateName, tp.data.testPlan?.summary);
console.log('rows', tp.data.testPlan?.timeline?.rows?.map(r => ({ task: r.taskId, days: r.segments.map(s => `${s.day} ${s.start}-${s.end}`), equipment: r.segments.map(s => s.equipmentId) })));
console.log('workspace', tp.data.workspace?.page, tp.data.workspace?.projectId, tp.data.workspace?.testPlanId);
const detail2 = await call('/api/lims/project?projectId=PRJ-1001');
console.log('persisted test plans', detail2.data.testPlans?.map(p => p.id));
const all = await call('/api/lims/test-plan', { projectId: 'PRJ-1002' });
console.log('PRJ-1002 all', all.data.testPlan?.templateName, all.data.testPlan?.summary, all.data.testPlan?.timeline?.rows?.map(r => r.taskId));
await client.close();
