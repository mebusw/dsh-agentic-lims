import { MongoClient } from 'mongodb';
import { buildRoutes } from '../lib/routes.js';
import { seedDatabase } from '../lib/seed.js';
const client = await MongoClient.connect('mongodb://127.0.0.1:27018');
const db = client.db('agentic_lims_test_template');
await db.dropDatabase();
await seedDatabase(db, { force: true });
const routes = buildRoutes({ db, config: { demoNow: '2026-10-30T08:00:00+08:00' } });
const call = async (path, body) => {
  const [pathname, query = ''] = path.split('?');
  const route = routes.find((r) => r.path === pathname && r.methods.includes(body ? 'POST' : 'GET'));
  const res = await route.fetch(new Request(`http://x${pathname}${query ? `?${query}` : ''}`, body ? { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify(body) } : {}));
  return { status: res.status, data: await res.json() };
};
const templates = await call('/api/lims/templates');
const tpl4 = templates.data.templates.find((t) => t.id === 'TPL-004');
console.log('templates', templates.status, templates.data.templates.length, 'TPL-004 projects', tpl4.projects);
const detailBefore = await call('/api/lims/project?projectId=PRJ-1001');
console.log('before groups', detailBefore.data.groups.map((g) => `${g.templateId}:${g.tasks.length}`));
const mapped = await call('/api/lims/task-template', { taskId: 'TASK-2001', templateId: 'TPL-001', actor: 'test' });
console.log('mapped', mapped.status, mapped.data);
const detailAfter = await call('/api/lims/project?projectId=PRJ-1001');
console.log('after groups', detailAfter.data.groups.map((g) => `${g.templateId}:${g.tasks.length}`));
const templatesAfter = await call('/api/lims/templates');
const tpl1 = templatesAfter.data.templates.find((t) => t.id === 'TPL-001');
console.log('TPL-001 projects after', tpl1.projects);
const reset = await call('/api/lims/task-template', { taskId: 'TASK-2001', templateId: null, actor: 'test' });
console.log('reset', reset.status, reset.data);
const detailReset = await call('/api/lims/project?projectId=PRJ-1001');
console.log('reset groups', detailReset.data.groups.map((g) => `${g.templateId}:${g.tasks.length}`));
await db.dropDatabase();
await client.close();
