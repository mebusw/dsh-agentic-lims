import { MongoClient } from 'mongodb';
import { buildRoutes } from '../lib/routes.js';
import { seedDatabase } from '../lib/seed.js';
const client = await MongoClient.connect('mongodb://127.0.0.1:27018');
const db = client.db('agentic_lims_test_draft');
await db.dropDatabase();
await seedDatabase(db, { force: true });
const routes = buildRoutes({ db, config: { demoNow: '2026-10-27T08:00:00+08:00' } });
const call = async (path, body) => {
  const [pathname, query = ''] = path.split('?');
  const route = routes.find((r) => r.path === pathname && r.methods.includes(body ? 'POST' : 'GET'));
  const res = await route.fetch(new Request(`http://x${pathname}${query ? `?${query}` : ''}`, body ? { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify(body) } : {}));
  return { status: res.status, data: await res.json() };
};
const requests = await call('/api/lims/requests');
console.log('requests', requests.status, requests.data.requests.length, requests.data.requests.slice(0, 2).map((r) => `${r.id}:${r.name}:${r.templateId}`));
const prepared = await call('/api/lims/task-draft/prepare', { projectId: 'PRJ-1001', requestText: '下周把拉伸和耐久测试排掉，优先保交期', templateId: 'TPL-004' });
console.log('prepare', prepared.status, prepared.data.recommendation, prepared.data.matches.map((m) => `${m.taskId}:${m.confidence}`), prepared.data.drafts[0]);
const draft = prepared.data.drafts[0];
draft.name = '拉伸耐久补充测试';
draft.dueDate = '2026-11-12';
draft.effortHours = 8;
const created = await call('/api/lims/task-drafts', { projectId: 'PRJ-1001', drafts: [draft], actor: 'demo' });
console.log('created', created.status, created.data.created);
const project = await call('/api/lims/project?projectId=PRJ-1001');
console.log('project groups', project.data.groups.map((g) => `${g.templateId}:${g.tasks.length}`), 'tasks', project.data.project.taskCount);
const plan = await call('/api/lims/test-plan', { projectId: 'PRJ-1001', templateId: 'TPL-004', actor: 'demo' });
console.log('test plan', plan.status, plan.data.testPlan?.summary, plan.data.testPlan?.timeline?.rows?.map((r) => r.taskId));
await db.dropDatabase();
await client.close();
