import { MongoClient } from 'mongodb';
import { buildRoutes } from '../lib/routes.js';
import { ensureIndexes, seedDatabase } from '../lib/seed.js';

const client = await MongoClient.connect('mongodb://127.0.0.1:27018', { serverSelectionTimeoutMS: 3000 });
const db = client.db('agentic_lims_test');
await db.dropDatabase();
await ensureIndexes(db);
console.log('seed', await seedDatabase(db));
const routes = buildRoutes({ db, config: { demoNow: '2026-10-30T08:00:00+08:00' } });
const call = async (path, body) => {
  const [p, q] = path.split('?');
  const route = routes.find(r => r.path === p);
  const res = await route.fetch(new Request(`http://x${p}${q ? `?${q}` : ''}`, body ? { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify(body) } : {}));
  const data = await res.json();
  console.log(`\n=== ${path} -> ${res.status}`);
  return data;
};
const health = await call('/api/lims/health');
console.log(health);
const overview = await call('/api/lims/overview');
console.log({ stats: overview.stats, tasks: overview.tasks.length, alerts: overview.alerts.length, timeline: overview.timeline.days.length });
const plans = await call('/api/lims/plans', { taskId: 'TASK-2005', count: 3 });
console.log(plans.plans.map(p => ({ id: p.id, st: p.status, score: p.score, start: p.startAt, end: p.endAt, eq: p.resources.equipment.id, person: p.resources.person.id })));
console.log('workspace', plans.workspace.revision, plans.workspace.page);
const ws = await call('/api/lims/workspace');
console.log('ws plans', ws.plans.length, ws.message);
const confirm = await call('/api/lims/confirm', { planId: plans.plans[0].id });
console.log('confirm', confirm.ok, confirm.simulated, confirm.allocations, confirm.plan?.status);
const after = await call('/api/lims/overview');
console.log('after stats', after.stats, 'tasks', after.tasks.filter(t => t.id === 'TASK-2005'));
const explain = await call('/api/lims/explain', { resourceId: 'EQ-004', taskId: 'TASK-2003' });
console.log(explain.usable, explain.reasons);
const analytics = await call('/api/lims/analytics');
console.log(analytics.summary, analytics.bottleneck);
const simulate = await call('/api/lims/simulate', { equipmentType: 'HPLC', addCount: 1 });
console.log(simulate.scenario);
const audit = await call('/api/lims/audit');
console.log('audit', audit.events.map(e => e.summary));
await client.close();
