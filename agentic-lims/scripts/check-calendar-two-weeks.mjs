import { MongoClient } from 'mongodb';
import { buildRoutes } from '../lib/routes.js';
const client = await MongoClient.connect('mongodb://127.0.0.1:27018');
const db = client.db('agentic_lims');
const routes = buildRoutes({ db, config: { demoNow: '2026-10-27T08:00:00+08:00' } });
const route = routes.find((r) => r.path === '/api/lims/resource-schedule');
const res = await route.fetch(new Request('http://x/api/lims/resource-schedule?weekStart=2026-10-26&weekCount=2'));
const data = await res.json();
console.log(res.status, { weekCount: data.weekCount, days: data.days.length, schedules: data.summary.schedules, resources: data.summary.resources, withPlan: data.summary.withPlan, withoutPlan: data.summary.withoutPlan });
for (const task of data.tasks) console.log(task.id, task.name);
await client.close();
